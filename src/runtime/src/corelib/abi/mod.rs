//! Builtin ABI v2 (runtime-audit P1-8): typed builtins.
//!
//! A builtin is a plain typed Rust function inside a `#[z42_macros::builtins]` module:
//!
//! ```ignore
//! #[builtin(name = "__int32_parse")]
//! pub fn int32_parse(s: &str) -> Result<i64, BuiltinError> { … }
//! ```
//!
//! The macro is the single source of truth. It generates the argument-reading wrapper
//! (arguments come straight out of the caller's register file by register index — see
//! [`RegArgs`] — or out of a plain slice for callers that hold one), a [`BuiltinDesc`],
//! and the module's `DESCS`, which the builtin table concatenates. Errors are typed
//! ([`BuiltinError`]): each kind is one stdlib exception class, `Internal` is fatal.
//!
//! Pieces:
//! - [`FromArg`] — one impl per Rust parameter type (`&str`, `i64`, `Option<&str>`, …):
//!   null / type checks happen here, with typed errors;
//! - [`IntoRet`] — one impl per Rust result type, including [`Blocking`];
//! - [`PlainArg`] / [`PlainRet`] — the plain-data types a `blocking` builtin may take /
//!   return (its body runs parked: it cannot see the heap, so it cannot allocate);
//! - [`error`] — `BuiltinError` and the one place that turns it into a thrown z42
//!   exception or a fatal VM error (both engines go through it).

mod args;
pub(crate) mod error;
mod ret;

pub use args::{ArgAt, ArgSource, FromArg, PlainArg, RefArg, RegArgs};
pub use error::{BuiltinError, FieldInit};
pub use ret::{Blocking, IntoRet, PlainRet, Then};

use crate::metadata::Value;
use crate::vm_context::VmContext;

/// Kind of a builtin parameter, as the Rust signature declares it (descriptor data,
/// for diagnostics and future checks — dispatch never consults it).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ParamKind {
    /// `i64` (also accepts a boxed integer).
    I64,
    /// `f64` (also accepts an integer).
    F64,
    Bool,
    Char,
    /// `&str` / `String` — non-null.
    Str,
    /// `Option<&str>` / `Option<String>` — null allowed.
    OptStr,
    /// A `ref` / `out` argument ([`RefArg`]).
    Ref,
    /// `Vec<u8>` — a non-null `byte[]`, copied out.
    Bytes,
    /// `Option<Vec<u8>>` — a `byte[]` or null.
    OptBytes,
    /// `Vec<String>` — a non-null `string[]` of non-null strings, copied out.
    StrArray,
    /// Any value (`&Value` / `Value`).
    Any,
}

/// Kind of a builtin's result.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RetKind {
    /// No value — the call writes nothing to its destination register.
    Void,
    I64,
    F64,
    Bool,
    Char,
    Str,
    /// A string or null.
    OptStr,
    /// A fresh `byte[]` (`Vec<u8>`).
    Bytes,
    /// A fresh `string[]` (`Vec<String>`).
    StrArray,
    /// Any value.
    Any,
}

/// Descriptor flags.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct BuiltinFlags {
    /// The body runs with the context parked (GC may run meanwhile).
    pub blocking: bool,
    /// No side effects, result depends only on the arguments (a future JIT intrinsic
    /// candidate). Informational.
    pub pure: bool,
    /// May run z42 code (callbacks, getters, initializers): a folded call of its
    /// `[Native]` wrapper keeps the wrapper's frame (`interp::forward`), so an exception
    /// thrown in that code — or a fatal report — shows the same stack as unfolded.
    pub reenters: bool,
}

/// A failed call, boxed: the error path is cold, and a one-word error keeps the call's
/// `Result` as small as the value it carries (it is returned on every builtin call).
pub type Fault = Box<BuiltinError>;

/// What a builtin call produces: its value (`None` = void) or a [`Fault`].
pub type CallResult = Result<Option<Value>, Fault>;

/// Entry reading the arguments from a register file: `this` (a receiver not held in a
/// register — the vcall short-circuit), then `regs[idx[i]]`.
pub type RegsEntry = fn(&VmContext, Option<Value>, &[Value], &[u32]) -> CallResult;
/// Entry reading the arguments from a slice.
pub type SliceEntry = fn(&VmContext, &[Value]) -> CallResult;

/// One typed builtin, generated by `#[builtins]`.
#[derive(Clone, Copy)]
pub struct BuiltinDesc {
    pub name: &'static str,
    pub params: &'static [ParamKind],
    pub ret: RetKind,
    pub flags: BuiltinFlags,
    pub call_regs: RegsEntry,
    pub call_slice: SliceEntry,
}

impl std::fmt::Debug for BuiltinDesc {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("BuiltinDesc")
            .field("name", &self.name).field("params", &self.params)
            .field("ret", &self.ret).field("flags", &self.flags)
            .finish()
    }
}

/// Total length of `parts` (compile time; the `#[builtins]` expansion and the table).
pub const fn descs_len(parts: &[&[BuiltinDesc]]) -> usize {
    let mut n = 0;
    let mut i = 0;
    while i < parts.len() { n += parts[i].len(); i += 1; }
    n
}

fn placeholder_slice(_: &VmContext, _: &[Value]) -> CallResult {
    Err(BuiltinError::Internal("builtin descriptor placeholder called".into()).into())
}
fn placeholder_regs(_: &VmContext, _: Option<Value>, _: &[Value], _: &[u32]) -> CallResult {
    Err(BuiltinError::Internal("builtin descriptor placeholder called".into()).into())
}

/// `parts` concatenated (compile time). `N` must be [`descs_len`]`(parts)`.
pub const fn concat_descs<const N: usize>(parts: &[&[BuiltinDesc]]) -> [BuiltinDesc; N] {
    // Filler only so the array can be built in a const fn; every slot is overwritten.
    let mut out = [BuiltinDesc {
        name: "", params: &[], ret: RetKind::Void,
        flags: BuiltinFlags { blocking: false, pure: false, reenters: false },
        call_regs: placeholder_regs, call_slice: placeholder_slice,
    }; N];
    let mut k = 0;
    let mut i = 0;
    while i < parts.len() {
        let mut j = 0;
        while j < parts[i].len() { out[k] = parts[i][j]; k += 1; j += 1; }
        i += 1;
    }
    assert!(k == N, "concat_descs: N does not match the parts");
    out
}

